"""Scaffold: copy the vault skeleton into a repo and vendor the tool."""
from __future__ import annotations

import json
import shutil
from pathlib import Path

from . import util
from .util import info, warn

FOLDERS = [
    "00-Inbox", "01-Projects", "02-Areas", "03-Resources",
    "04-Content/Talks", "04-Content/Courses", "04-Content/Articles",
    "05-Dashboards", "06-Canvases", "07-Daily", "08-Archive", "09-Attachments", "Templates",
]

VAULT_GITIGNORE = """# per-user Obsidian state: never commit
.obsidian/workspace.json
.obsidian/workspace-mobile.json
.obsidian/cache
.obsidian/plugins/*/data.json
.obsidian/plugins/*/*.map
.trash/
.DS_Store
"""

VENDOR_SKIP = shutil.ignore_patterns(
    "__pycache__", "*.pyc", "*.pyo", ".DS_Store", ".git", "node_modules", "*.egg-info",
)


def template_root() -> Path:
    return util.tool_root() / "templates" / "vault"


def values(repo: Path, cfg: dict):
    areas = cfg.get("areas") or []
    tags = cfg.get("domain_tags") or []
    return {
        "project": cfg["project"],
        "project_slug": util.slug(cfg["project"]),
        "vault_dir": cfg["vault_dir"],
        "repo_path": str(repo),
        "date": util.TODAY,
        "first_area": areas[0] if areas else "Architecture",
        "areas_list": ", ".join("`%s/`" % a for a in areas) if areas else "`Architecture/`",
        "areas_links": "\n".join("- [[%s]]" % a for a in areas) if areas else "- [[Architecture]]",
        "domain_tags": ", ".join("`%s`" % t for t in tags) if tags else "`codebase`, `tooling`",
    }


def vendor_tool(repo: Path) -> str:
    """Copy this tool into <repo>/.vault-forge/ so the repo carries it."""
    src = util.tool_root()
    dest = repo / ".vault-forge"
    dest.mkdir(parents=True, exist_ok=True)
    for name in ("vaultforge", "templates"):
        target = dest / name
        if target.exists():
            shutil.rmtree(target)
        shutil.copytree(src / name, target, ignore=VENDOR_SKIP)
    entry = dest / "vault-forge"
    shutil.copy2(src / "vault-forge", entry)
    entry.chmod(0o755)
    return str(dest)


def structure(repo: Path, cfg: dict, force: bool = False):
    """Create folders, Obsidian config, templates and the three root notes."""
    vault = util.vault_path(repo, cfg)
    tmpl = template_root()
    if not tmpl.exists():
        util.die("template tree missing at %s" % tmpl)
    written, kept = [], []

    for folder in FOLDERS:
        (vault / folder).mkdir(parents=True, exist_ok=True)

    # .obsidian config, snippets, theme
    for src in sorted((tmpl / ".obsidian").rglob("*")):
        if not src.is_file():
            continue
        rel = src.relative_to(tmpl / ".obsidian")
        if rel.name == "community-plugins.json":
            continue
        dest = vault / ".obsidian" / rel
        if dest.exists() and not force:
            kept.append(str(rel))
            continue
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, dest)
        written.append(".obsidian/%s" % rel)
    plugins = vault / ".obsidian" / "community-plugins.json"
    if not plugins.exists() or force:
        plugins.write_text("[]\n")
        written.append(".obsidian/community-plugins.json")

    # note templates, rendered with the project's first area
    vals = values(repo, cfg)
    for src in sorted((tmpl / "Templates").glob("*.md")):
        dest = vault / "Templates" / src.name
        if dest.exists() and not force:
            kept.append("Templates/%s" % src.name)
            continue
        dest.write_text(util.render(src.read_text(), vals))
        written.append("Templates/%s" % src.name)

    # bases
    for src in sorted((tmpl / "05-Dashboards").glob("*.base")):
        dest = vault / "05-Dashboards" / src.name
        if dest.exists() and not force:
            kept.append("05-Dashboards/%s" % src.name)
            continue
        shutil.copy2(src, dest)
        written.append("05-Dashboards/%s" % src.name)

    # root notes rendered from .tmpl
    for name, dest_rel in (
        ("README.md.tmpl", "README.md"),
        ("Home.md.tmpl", "Home.md"),
        ("05-Dashboards/Dashboard.md.tmpl", "05-Dashboards/Dashboard.md"),
    ):
        dest = vault / dest_rel
        if dest.exists() and not force:
            kept.append(dest_rel)
            continue
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(util.render((tmpl / name).read_text(), vals))
        written.append(dest_rel)

    ignore = vault / ".gitignore"
    if not ignore.exists():
        ignore.write_text(VAULT_GITIGNORE)
        written.append(".gitignore")

    marker = vault / ".vault-forge-managed"
    marker.write_text(
        "Generated by vault-forge %s on %s.\n"
        "Conventions: README.md at the vault root. Tool: %s/.vault-forge/\n"
        "Safe to delete; it only marks the vault as agent-maintained.\n"
        % (util.TOOL_VERSION, util.TODAY, cfg["vault_dir"])
    )
    return written, kept


def init(repo: Path, args) -> int:
    cfg = util.load_config(repo) if (repo / ".vault-forge" / "forge.json").exists() else dict(util.DEFAULT_CONFIG)
    manifest_name = ""
    manifest = util.read_json(repo / "package.json", {})
    if isinstance(manifest, dict):
        manifest_name = str(manifest.get("name", "") or "")
    cfg["project"] = args.name or cfg.get("project") or manifest_name or repo.name
    cfg["vault_dir"] = args.dir or cfg.get("vault_dir") or "docs-vault"
    if args.areas:
        cfg["areas"] = [a.strip() for a in args.areas.split(",") if a.strip()]
    if args.tags:
        cfg["domain_tags"] = [t.strip() for t in args.tags.split(",") if t.strip()]

    vault = repo / cfg["vault_dir"]
    if vault.exists() and not vault.is_dir():
        util.die("%s exists and is not a directory" % vault)
    if vault.exists() and (vault / "README.md").exists() and not args.force:
        info("vault already initialised at %s (use --force to re-render templates)" % vault)

    written, kept = structure(repo, cfg, force=args.force)
    util.save_config(repo, cfg)
    vendored = vendor_tool(repo)

    info("vault:    %s" % vault)
    info("config:   %s/forge.json" % (repo / ".vault-forge"))
    info("tool:     %s/vault-forge (vendored, commit it)" % (repo / ".vault-forge"))
    info("areas:    %s" % (", ".join(cfg["areas"]) or "(derived on scan)"))
    info("written:  %d files" % len(written))
    if kept:
        info("kept:     %d existing files untouched" % len(kept))
    info("")
    info("next:  ./.vault-forge/vault-forge build     # scan the repo, seed notes, build the index")
    info("       ./.vault-forge/vault-forge validate  # the gate: 0 errors or a non-zero exit")
    return 0
