"""Search index: build, then answer queries from it."""
from __future__ import annotations

import json
import re
from pathlib import Path

from . import util
from .util import info
from .vault import Note, is_template, load_vault

INDEX_DIR = "index"
TOKEN = re.compile(r"[a-z0-9][a-z0-9_.:/-]{1,}")


def build(repo: Path, cfg: dict) -> int:
    vault = util.vault_path(repo, cfg)
    if not vault.exists():
        util.die("no vault at %s; run init first" % vault)
    notes = load_vault(vault)
    records, chunks = [], []
    for note in notes:
        if is_template(note):
            continue
        records.append({
            "path": note.path,
            "title": note.title,
            "type": note.type,
            "status": note.status,
            "tags": note.tags,
            "area": str(note.frontmatter.get("area", "")),
            "headings": note.headings,
            "links": [link["target"] for link in note.links],
            "embeds": [embed["target"] for embed in note.embeds],
            "summary": note.first_paragraph(),
            "words": len(re.findall(r"\S+", note.body)),
            "lines": len(note.text.splitlines()),
        })
        chunks.extend(note.chunks())

    index_dir = vault / INDEX_DIR
    index_dir.mkdir(parents=True, exist_ok=True)
    payload = {
        "tool": "vault-forge",
        "version": util.TOOL_VERSION,
        "generated_at": util.now_stamp(),
        "source_commit": util.git(repo, "rev-parse", "HEAD").strip(),
        "vault": str(vault),
        "counts": {
            "notes": len(records),
            "chunks": len(chunks),
            "words": sum(record["words"] for record in records),
        },
        "notes": records,
    }
    util.write_json(index_dir / "vault-index.json", payload)
    with (index_dir / "chunks.jsonl").open("w", encoding="utf-8") as handle:
        for chunk in chunks:
            handle.write(json.dumps(chunk, ensure_ascii=False) + "\n")
    (index_dir / "index.md").write_text(render_catalog(records, payload), encoding="utf-8")

    if not cfg.get("commit_index", True):
        ignore = vault / ".gitignore"
        text = ignore.read_text() if ignore.exists() else ""
        if "index/" not in text:
            ignore.write_text(text.rstrip() + "\nindex/\n")

    info("index: %s" % (vault / INDEX_DIR))
    info("  notes:  %d" % len(records))
    info("  chunks: %d" % len(chunks))
    info("  words:  %d" % payload["counts"]["words"])
    info("  commit: %s" % payload["source_commit"][:12] if payload["source_commit"] else "  commit: -")
    return 0


def render_catalog(records, payload) -> str:
    lines = [
        "# Vault index",
        "",
        "> Generated by `vault-forge index` on %s from commit %s. Do not hand-edit." % (
            payload["generated_at"], (payload["source_commit"] or "-")[:12]),
        "> %d notes, %d chunks. Agents: search this first with `./.vault-forge/vault-forge search \"query\"`." % (
            payload["counts"]["notes"], payload["counts"]["chunks"]),
        "",
    ]
    by_folder = {}
    for record in sorted(records, key=lambda r: r["path"]):
        folder = record["path"].rsplit("/", 1)[0] if "/" in record["path"] else "(root)"
        by_folder.setdefault(folder, []).append(record)
    for folder in sorted(by_folder):
        lines.append("## %s" % folder)
        lines.append("")
        for record in by_folder[folder]:
            summary = record["summary"] or "(no summary line)"
            lines.append("- [[%s]]: %s" % (record["title"], summary[:120]))
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def load_chunks(vault: Path):
    path = vault / INDEX_DIR / "chunks.jsonl"
    if not path.exists():
        util.die("no index at %s; run: ./.vault-forge/vault-forge index" % path)
    out = []
    with path.open(encoding="utf-8") as handle:
        for line in handle:
            line = line.strip()
            if line:
                out.append(json.loads(line))
    return out


def search(repo: Path, cfg: dict, query: str, limit: int = 8, tag: str = "", kind: str = "",
           as_json: bool = False) -> int:
    vault = util.vault_path(repo, cfg)
    chunks = load_chunks(vault)
    tokens = TOKEN.findall(query.lower())
    if not tokens:
        util.die("empty query")
    phrase = query.strip().lower()

    scored = []
    for chunk in chunks:
        text = chunk["text"].lower()
        title = chunk["title"].lower()
        heading = chunk["heading"].lower()
        path = chunk["path"].lower()
        score = 0.0
        matched = 0
        for token in tokens:
            hits = text.count(token)
            if hits:
                matched += 1
                score += 1.0 + min(hits, 6) * 0.25
            if token in title:
                score += 6.0
            if token in heading:
                score += 4.0
            if token in path:
                score += 3.0
        if phrase and phrase in text:
            score += 8.0
        if matched == len(tokens) and len(tokens) > 1:
            score += 5.0
        if not score:
            continue
        scored.append((score, matched, chunk))
    scored.sort(key=lambda row: (-row[0], row[2]["path"], row[2]["start_line"]))

    if tag or kind:
        keep = []
        for score, matched, chunk in scored:
            record = _record_for(vault, chunk["path"])
            if kind and (not record or record.get("type") != kind):
                continue
            if tag:
                tags = (record or {}).get("tags", [])
                if tag.lower() not in [str(t).lower() for t in tags]:
                    continue
            keep.append((score, matched, chunk))
        scored = keep

    scored = scored[:limit]
    total = len(tokens)
    if as_json:
        info(json.dumps([{
            "score": round(score, 2),
            "terms_matched": "%d/%d" % (matched, total),
            "path": chunk["path"],
            "line": chunk["start_line"],
            "heading": chunk["heading"],
            "text": util.one_line(chunk["text"], 400),
        } for score, matched, chunk in scored], indent=2, ensure_ascii=False))
        return 0
    if not scored:
        info("no match for %r in %s" % (query, vault / INDEX_DIR))
        return 1
    for score, matched, chunk in scored:
        snippet = util.one_line(chunk["text"], 200)
        info("%-52s:%d  [%0.1f %d/%d]  %s" % (
            chunk["path"], chunk["start_line"], score, matched, total, chunk["heading"]))
        info("    %s" % snippet)
    return 0


_RECORD_CACHE = {}


def _record_for(vault: Path, path: str):
    if vault not in _RECORD_CACHE:
        payload = util.read_json(vault / INDEX_DIR / "vault-index.json", {})
        _RECORD_CACHE[vault] = {record["path"]: record for record in payload.get("notes", [])}
    return _RECORD_CACHE[vault].get(path)
